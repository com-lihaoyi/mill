package mill.javalib.internal

import utest.*

object GeneratedBuildSourcesTests extends TestSuite {

  private val buildFile = os.root / "workspace" / "build.mill"

  private def marker(path: os.Path) = s"///SOURCE_CODE_START:$path\n"

  // Shaped like what CodeGen generates for a root build file
  private val buildHeader =
    s"""// Generated by Mill
       |package build_
       |
       |import build_.{package_ => build}
       |
       |object package_ extends package_ {
       |  override lazy val millDiscover: _root_.mill.api.Discover = _root_.mill.api.Discover[this.type]
       |}
       |
       |abstract class package_
       |    extends _root_.mill.util.MainRootModule { this: package_.type =>
       |${marker(buildFile)}""".stripMargin
  private val buildOriginal =
    """//| mill-version: 1.4.0
      |package build
      |
      |import mill.*, scalalib.*
      |
      |object foo extends ScalaModule {
      |  def scalaVersion = "3.8.4"
      |}
      |""".stripMargin
  // CodeGen comments out the package statement, keeping its length
  private val buildUserCode = buildOriginal.replace("\npackage build\n", "\n//ckage build\n")
  // CodeGen drops the trailing new line of the build file, and writes its own before the footer
  private val buildFooter = "}"

  // Shaped like what CodeGen generates for a package.mill file with an object `package`,
  // which gets turned into a class, with its parents moved to a stub after the user code
  private val packageFile = os.root / "workspace" / "thing" / "package.mill"
  private val packageHeader =
    s"""// Generated by Mill
       |package build_.thing
       |
       |import build_.{package_ => build}
       |
       |object package_ extends package_ {
       |
       |}
       |
       |
       |${marker(packageFile)}""".stripMargin
  private val packageOriginal =
    """package build.thing
      |
      |import mill.*, scalalib.*
      |
      |object `package` extends ScalaModule {
      |  def scalaVersion = "3.8.4"
      |}
      |""".stripMargin
  private val packageUserCode =
    """//ckage build.thing
      |
      |import mill.*, scalalib.*
      |
      |class  package_  extends _MillRootMo {
      |  def scalaVersion = "3.8.4"
      |}
      |""".stripMargin
  private val packageFooter =
    "\nabstract class _MillRootMo(using _root_.sourcecode.Line, _root_.sourcecode.File) " +
      "extends _root_.mill.api.internal.SubfolderModule(_root_.build_.package_.millDiscover), ScalaModule"

  // Shaped like what CodeGen generates for a non-build script
  private val scriptFile = os.root / "workspace" / "helpers.mill"
  private val scriptHeader =
    s"""// Generated by Mill
       |package build_
       |
       |object helpers_ {
       |${marker(scriptFile)}""".stripMargin
  private val scriptOriginal =
    """def greeting = "hello"
      |""".stripMargin
  private val scriptFooter = "}\n\nexport helpers_._\n"

  def tests: Tests = Tests {
    test("sanity") {
      // The samples above must hold the invariant CodeGen maintains
      assert(buildUserCode.length == buildOriginal.length)
      assert(buildUserCode.linesIterator.size == buildOriginal.linesIterator.size)
      assert(packageUserCode.length == packageOriginal.length)
    }

    test("userCodeStart") {
      test("buildFile") {
        val generated = buildHeader + buildUserCode + buildFooter
        val start = GeneratedBuildSources.userCodeStart(generated)
        assert(
          start.map(_.originalSource) == Some(buildFile),
          start.map(_.offset) == Some(buildHeader.length),
          start.map(_.lineIdx) == Some(buildHeader.count(_ == '\n'))
        )
        // The line the user code starts on is the first line of the original source
        val lineIdx = start.get.lineIdx
        assert(generated.linesIterator.drop(lineIdx).next() == "//| mill-version: 1.4.0")
      }

      test("markerAtStart") {
        val generated = marker(scriptFile) + scriptOriginal
        val start = GeneratedBuildSources.userCodeStart(generated)
        assert(start == Some(GeneratedBuildSources.UserCodeStart(
          scriptFile,
          marker(scriptFile).length,
          1
        )))
      }

      test("crlf") {
        // Windows checkouts may have CRLF line endings in the user code. The marker line
        // itself is written by CodeGen, but trailing whitespace shouldn't end up in the path.
        val generated = s"// Generated by Mill\r\n///SOURCE_CODE_START:$buildFile\r\nfoo\r\n"
        val start = GeneratedBuildSources.userCodeStart(generated)
        assert(
          start.map(_.originalSource) == Some(buildFile),
          start.map(_.lineIdx) == Some(2)
        )
      }

      test("noMarker") {
        val generated = "package build_\n//SOURCECODE_ORIGINAL_CODE_START_MARKER\nfoo\n"
        assert(GeneratedBuildSources.userCodeStart(generated) == None)
      }

      test("markerNotAtLineStart") {
        // Only a whole line starting with the marker counts
        val generated = s"val s = \"///SOURCE_CODE_START:$buildFile\"\nfoo\n"
        assert(GeneratedBuildSources.userCodeStart(generated) == None)
      }

      test("unterminatedMarker") {
        assert(GeneratedBuildSources.userCodeStart(marker(buildFile).stripSuffix("\n")) == None)
      }

      test("relativePath") {
        assert(
          GeneratedBuildSources.userCodeStart("///SOURCE_CODE_START:build.mill\nfoo\n") == None
        )
      }
    }

    test("wrappers") {
      def check(header: String, userCode: String, footer: String, original: String) = {
        val res = GeneratedBuildSources.wrappers(header + userCode + footer, original.length)
        assert(res == Some((top = header, bottom = footer)))
      }

      test("buildFile") - check(buildHeader, buildUserCode, buildFooter, buildOriginal)
      test("packageObject") - check(packageHeader, packageUserCode, packageFooter, packageOriginal)
      test("script") - check(scriptHeader, scriptOriginal, scriptFooter, scriptOriginal)
      test("emptyFooter") - check(buildHeader, buildUserCode, "", buildOriginal)

      test("originalLongerThanUserCode") {
        // Happens if the build file was edited since the source was generated
        val generated = buildHeader + buildUserCode + buildFooter
        val res = GeneratedBuildSources.wrappers(
          generated,
          buildOriginal.length + buildFooter.length + 1
        )
        assert(res == None)
      }

      test("noMarker") {
        assert(GeneratedBuildSources.wrappers("package build_\nfoo\n", 4) == None)
      }
    }
  }
}
